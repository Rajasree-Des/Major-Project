BETA_CANDIDATES = (0.0, 0.25, 0.5, 0.75, 1.0)

METHOD_DOC = {
    "name": "synthetic_forward_consistency_refinement",
    "summary": (
        "Deterministic post-processing: apply the project's noise-free synthetic forward operator "
        "(masked Gaussian blur sigma=1.2 HR px + area downsample in Kelvin) to the SwinIR HR estimate, "
        "form the LR residual against the observed LR thermal input, upsample by block replication, "
        "smooth with the same Gaussian kernel, and add beta times that correction in Kelvin. "
        "This is a consistency correction under the synthetic training degradation, not a radiative-transfer model."
    ),
    "assumptions": [
        "The synthetic LR was generated by blur+downsample in Kelvin (noise ignored for consistency).",
        "SwinIR already estimates HR structure; correction is limited to the blur's frequency band.",
        "Scene z-score stats are the same used in preprocessing (for Kelvin conversion only).",
    ],
    "limitations": [
        "0.05 K degradation noise makes exact consistency impossible; residual correction is approximate.",
        "Does not model real TIRS PSF, atmospheric effects, or emissivity.",
        "beta tuned on validation patches only; single validation scene.",
    ],
    "uses_hr_pixels_for_prediction": False,
}


def tune_beta(
    root: Path,
    scene_ids: Sequence[str],
    model: torch.nn.Module,
    degradation: DegradationConfig,
    stats_map: dict,
    tune_patch_indices: list[int],
    batch_size: int,
) -> tuple[float, list[dict[str, Any]]]:
    """Pick beta minimizing pooled Kelvin RMSE on tune indices (HR used only for scoring)."""
    ds = ThermalSRDataset(root, degradation=degradation, scene_ids=list(scene_ids), patch_indices=tune_patch_indices)
    loader = torch.utils.data.DataLoader(ds, batch_size=batch_size, shuffle=False, num_workers=0, collate_fn=collate_sr)
    records: list[dict[str, Any]] = []
    best_beta, best_rmse = 0.0, float("inf")
    for beta in BETA_CANDIDATES:
        conf = ConsistencyRefinementConfig(beta=beta, degradation=degradation)
        sum_sq_k, n = 0.0, 0
        t0 = time.perf_counter()
        for batch in loader:
            lr_raw = batch["lr"]
            lr = prepare_lr(lr_raw)
            hr = batch["hr"]
            valid = batch["hr_valid_mask"] & torch.isfinite(hr)
            with torch.no_grad():
                sr = model(lr)
                refined = refine_torch_batch(lr_raw, sr, batch["lr_valid_mask"], stats_map[batch["scene_id"][0]], conf)
            for i in range(refined.shape[0]):
                st = stats_map[batch["scene_id"][i]]
                v = valid[i]
                if not v.any():
                    continue
                diff_k = (refined[i][v].double() * st.std + st.mean) - (hr[i][v].double() * st.std + st.mean)
                sum_sq_k += float((diff_k**2).sum())
                n += int(v.sum())
        rmse = (sum_sq_k / n) ** 0.5 if n else float("inf")
        elapsed = time.perf_counter() - t0
        records.append({"beta": beta, "tune_rmse_kelvin": rmse, "tune_valid_pixels": n, "seconds": elapsed})
        logger.info("tune beta=%.2f  tune RMSE Kelvin=%.5f  (%d px)", beta, rmse, n)
        if rmse < best_rmse:
            best_beta, best_rmse = beta, rmse
    return best_beta, records


def build_refined_context_fn(model, conf: ConsistencyRefinementConfig, stats_map: dict):
    def fn(lr_raw, lr_prep, lr_mask, scene_ids):
        with torch.no_grad():
            sr = model(lr_prep)
        outs = []
        for i in range(lr_prep.shape[0]):
            st = stats_map[scene_ids[i]]
            outs.append(refine_torch_batch(lr_raw[i : i + 1], sr[i : i + 1], lr_mask[i : i + 1], st, conf))
        return torch.cat(outs, dim=0)

    return fn


def load_frozen_beta(output_root: Path, cli_beta: float | None) -> float:
    if cli_beta is not None:
        return float(cli_beta)
    method_path = output_root / "METHOD.txt"
    if method_path.exists():
        return float(json.loads(method_path.read_text(encoding="utf-8"))["beta"])
    return 1.0


def add_delta_vs_swinir(per_scene: list[dict[str, Any]]) -> None:
    for s in per_scene:
        m = s.get("metrics")
        if not m or "swinir_consistency_refined" not in m:
            continue
        sw, rf = m["swinir_pretrained"], m["swinir_consistency_refined"]
        s["delta_vs_swinir_pretrained"] = {
            n: (rf[n] - sw[n]) if rf.get(n) is not None and sw.get(n) is not None else None for n in METRIC_NAMES
        }


def patch_distribution(rows: list[dict], base: str, refined: str) -> dict[str, Any]:
    scored = [r for r in rows if "excluded" not in r]
    deltas = [r[f"{base}_rmse_kelvin"] - r[f"{refined}_rmse_kelvin"] for r in scored]
    arr = np.array(deltas, dtype=np.float64)
    return {
        "rmse_kelvin_improvement_vs_swinir": {
            "mean": float(arr.mean()),
            "median": float(np.median(arr)),
            "p10": float(np.percentile(arr, 10)),
            "p90": float(np.percentile(arr, 90)),
            "fraction_improved": float((arr > 0).mean()),
        }
    }


def save_gain_loss_figures(
    rows: list[dict],
    ds: ThermalSRDataset,
    methods: list[Method],
    conf: ConsistencyRefinementConfig,
    stats_map: dict,
    out_dir: Path,
    n_each: int = 2,
) -> list[str]:
    scored = sorted(
        [r for r in rows if "excluded" not in r],
        key=lambda r: r["swinir_pretrained_rmse_kelvin"] - r["swinir_consistency_refined_rmse_kelvin"],
    )
    paths: list[str] = []
    fig_dir = out_dir / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    model = methods[1][2]
    ctx = build_refined_context_fn(model, conf, stats_map)
    for label, subset in [("improved", scored[-n_each:]), ("worsened", scored[:n_each])]:
        for r in subset:
            sample = collate_sr([ds[r["position"]]])
            lr_raw, lr = sample["lr"], prepare_lr(sample["lr"])
            with torch.no_grad():
                preds = {
                    "Bicubic": methods[0][2](lr)[0],
                    "SwinIR": model(lr)[0],
                    "Refined": ctx(lr_raw, lr, sample["lr_valid_mask"], sample["scene_id"])[0],
                }
            path = fig_dir / f"{label}_patch_{r['patch_id']}.png"
            save_comparison_figure(
                sample["lr"][0],
                preds,
                sample["hr"][0],
                sample["hr_valid_mask"][0] & torch.isfinite(sample["hr"][0]),
                path,
                title=f"{r['scene_id']} patch {r['patch_id']} ({label} vs SwinIR RMSE K)",
                subtitle="synthetic x2 SR vs 30 m reference (not real 15 m thermal accuracy)",
            )
            paths.append(str(path.relative_to(out_dir)))
    return paths


def patch_distribution_by_scene(
    rows: list[dict], base: str, refined: str
) -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for sid in sorted({r["scene_id"] for r in rows if "excluded" not in r}):
        scene_rows = [r for r in rows if r["scene_id"] == sid and "excluded" not in r]
        out[sid] = patch_distribution(scene_rows, base, refined)
    return out


def _git_head() -> str | None:
    import subprocess

    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], text=True, cwd=PROJECT_ROOT).strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None


def run_test_locked(args: argparse.Namespace) -> int:
    """One-time locked test eval; beta and degradation fixed; no tuning."""
    import hashlib
    import platform
    from datetime import datetime, timezone

    out_root = args.output_root.resolve()
    test_dir = out_root / "test_locked"
    if test_dir.exists() and any(test_dir.iterdir()):
        logger.error("Refusing to overwrite non-empty %s", test_dir)
        return 1

    beta = load_frozen_beta(out_root, args.beta)
    logger.info("Frozen beta=%.2f from METHOD.txt / CLI (no tuning on test)", beta)
    logger.warning(TEST_LOCK_LABEL)

    set_seed(args.seed)
    torch.set_grad_enabled(False)
    root = args.processed_root.resolve()
    split = load_scene_split_manifest(args.split_manifest, list_processed_scene_ids(root))
    test_scenes = list(scene_ids_for_role(split, "test"))
    expected = [
        "LC08_L2SP_144048_20240427_02_T1",
        "LC09_L2SP_137042_20230110_02_T1",
    ]
    if sorted(test_scenes) != sorted(expected):
        logger.warning("Test scenes from manifest %s (expected %s)", test_scenes, expected)

    degradation = DegradationConfig(scale=args.scale, base_seed=args.seed)
    methods_base, model_info = build_methods(args)
    model = methods_base[1][2]
    meta_ds = ThermalSRDataset(root, degradation=degradation, scene_ids=test_scenes)
    stats_map = {sid: m.thermal_norm for sid, m in meta_ds.base_dataset.metadata_by_scene.items()}
    conf = ConsistencyRefinementConfig(beta=beta, degradation=degradation)
    refined_key = "swinir_consistency_refined"
    methods: list[Method] = [
        methods_base[0],
        methods_base[1],
        (refined_key, f"SwinIR + synthetic forward consistency (beta={beta})", model),
    ]
    ctx_fn = build_refined_context_fn(model, conf, stats_map)

    cmd = "py -W ignore -m evaluation.evaluate_physics_refinement --role test_locked"
    t0 = time.perf_counter()
    result = evaluate_role(
        root,
        test_scenes,
        methods,
        degradation=degradation,
        selection=args.patch_selection,
        batch_size=args.batch_size,
        log_every=25,
        lr_context_method_keys=frozenset({refined_key}),
        lr_context_fns={refined_key: ctx_fn},
    )
    elapsed = time.perf_counter() - t0
    add_delta_vs_swinir(result["per_scene"])
    result["patch_distribution"] = patch_distribution(result["_rows"], "swinir_pretrained", refined_key)
    result["patch_distribution_by_scene"] = patch_distribution_by_scene(
        result["_rows"], "swinir_pretrained", refined_key
    )
    result.update(
        {
            "role": "test",
            "label": EXPERIMENT_LABEL,
            "lock_label": TEST_LOCK_LABEL,
            "experiment": "physics_refinement_v1_test_locked",
            "refinement": {
                **METHOD_DOC,
                "beta": beta,
                "frozen": True,
                "method_spec": str(out_root / "METHOD.txt"),
            },
            "split_manifest": str(args.split_manifest.resolve()),
            "split_manifest_sha256": hashlib.sha256(args.split_manifest.read_bytes()).hexdigest(),
            "processed_root": str(root),
            "degradation": degradation.to_dict(),
            "seed": args.seed,
            "limitations": LIMITATIONS
            + METHOD_DOC["limitations"]
            + [
                "LOCKED TEST: one-time report; do not use for model selection or parameter changes.",
                "Synthetic x2 reconstruction vs 30 m reference; not real 15 m thermal accuracy.",
            ],
            "training_performed": False,
            "timing": {
                "device": "cpu",
                "cpu": platform.processor(),
                "torch_threads": torch.get_num_threads(),
                "torch_version": torch.__version__,
                "role_total_s": elapsed,
            },
            "timestamp_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "model": model_info,
            "run_manifest": {
                "command": cmd,
                "beta": beta,
                "degradation": degradation.to_dict(),
                "scene_ids": test_scenes,
                "patch_selection": args.patch_selection,
                "git_commit": _git_head(),
            },
        }
    )
    rows_copy, ds_copy = result["_rows"], result["_dataset"]
    save_role_outputs(result, test_dir, methods, args.figures_per_scene)
    extra = save_gain_loss_figures(rows_copy, ds_copy, methods, conf, stats_map, test_dir, n_each=1)
    saved = json.loads((test_dir / "results.json").read_text(encoding="utf-8"))
    saved["figures"] = list(saved.get("figures", [])) + extra
    saved["patch_distribution"] = result["patch_distribution"]
    saved["patch_distribution_by_scene"] = result["patch_distribution_by_scene"]
    (test_dir / "results.json").write_text(json.dumps(saved, indent=2), encoding="utf-8")
    (test_dir / "run_manifest.json").write_text(json.dumps(result["run_manifest"], indent=2), encoding="utf-8")
    logger.info("Wrote %s (sanity passed: %s)", test_dir, result["sanity_checks"]["passed"])
    return 0 if result["sanity_checks"]["passed"] else 1


def main(argv: Sequence[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--role",
        choices=("validation", "test_locked"),
        default="validation",
        help="validation: Kerala experiment; test_locked: frozen beta on held-out test scenes only",
    )
    p.add_argument("--processed-root", type=Path, default=DEFAULT_ROOT)
    p.add_argument("--split-manifest", type=Path, default=DEFAULT_MANIFEST)
    p.add_argument("--output-root", type=Path, default=DEFAULT_OUTPUT)
    p.add_argument("--patch-selection", default="non_overlapping")
    p.add_argument("--tune-fraction", type=float, default=0.25)
    p.add_argument("--tune-seed", type=int, default=42)
    p.add_argument("--beta", type=float, default=None, help="Skip tuning and use this beta (e.g. 1.0)")
    p.add_argument("--batch-size", type=int, default=4)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--scale", type=int, default=2)
    p.add_argument("--variant", default="lightweight_x2")
    p.add_argument("--pretrained-checkpoint", default="auto")
    p.add_argument("--figures-per-scene", type=int, default=2)
    p.add_argument("--log-level", default="INFO")
    args = p.parse_args(argv)
    logging.basicConfig(level=getattr(logging, args.log_level.upper(), logging.INFO),
                        format="%(asctime)s | %(levelname)s | %(message)s")
    if args.role == "test_locked":
        return run_test_locked(args)
    out = args.output_root.resolve()
    if out.exists() and any(out.iterdir()):
        logger.error("Refusing to overwrite non-empty %s", out)
        return 1
    out.mkdir(parents=True)

    set_seed(args.seed)
    torch.set_grad_enabled(False)
    root = args.processed_root.resolve()
    split = load_scene_split_manifest(args.split_manifest, list_processed_scene_ids(root))
    val_scenes = list(scene_ids_for_role(split, "validation"))
    degradation = DegradationConfig(scale=args.scale, base_seed=args.seed)
    methods_base, model_info = build_methods(args)
    model = methods_base[1][2]
    meta_ds = ThermalSRDataset(root, degradation=degradation, scene_ids=val_scenes)
    stats_map = {sid: m.thermal_norm for sid, m in meta_ds.base_dataset.metadata_by_scene.items()}

    all_idx = select_patch_indices(meta_ds, args.patch_selection)
    rng = random.Random(args.tune_seed)
    tune_n = max(1, int(len(all_idx) * args.tune_fraction))
    tune_idx = sorted(rng.sample(all_idx, tune_n))
    eval_idx = [i for i in all_idx if i not in set(tune_idx)]

    if args.beta is not None:
        best_beta = float(args.beta)
        tune_records = [{"beta": best_beta, "source": "cli", "tune_rmse_kelvin": None}]
        logger.info("Using fixed beta=%.2f (tuning skipped)", best_beta)
    else:
        best_beta, tune_records = tune_beta(root, val_scenes, model, degradation, stats_map, tune_idx, args.batch_size)
    conf = ConsistencyRefinementConfig(beta=best_beta, degradation=degradation)
    refined_key = "swinir_consistency_refined"
    methods: list[Method] = [
        methods_base[0],
        methods_base[1],
        (refined_key, f"SwinIR + synthetic forward consistency (beta={best_beta})", model),
    ]
    ctx_fn = build_refined_context_fn(model, conf, stats_map)

    t0 = time.perf_counter()
    result = evaluate_role(
        root,
        val_scenes,
        methods,
        degradation=degradation,
        selection=args.patch_selection,
        batch_size=args.batch_size,
        log_every=25,
        lr_context_method_keys=frozenset({refined_key}),
        lr_context_fns={refined_key: ctx_fn},
        patch_indices_override=eval_idx,
    )
    elapsed = time.perf_counter() - t0
    result["patch_distribution"] = patch_distribution(result["_rows"], "swinir_pretrained", refined_key)
    result.update({
        "role": "validation",
        "label": EXPERIMENT_LABEL,
        "experiment": "physics_refinement_v1",
        "refinement": {
            **METHOD_DOC,
            "beta": best_beta,
            "beta_candidates": list(BETA_CANDIDATES),
            "tune_patch_count": len(tune_idx),
            "eval_patch_count": len(eval_idx),
            "tune_records": tune_records,
        },
        "split_manifest": str(args.split_manifest),
        "processed_root": str(root),
        "degradation": degradation.to_dict(),
        "limitations": LIMITATIONS + METHOD_DOC["limitations"],
        "training_performed": False,
        "timing": {"total_eval_s": elapsed, "device": "cpu"},
        "model": model_info,
    })
    val_dir = out / "validation"
    rows_copy, ds_copy = result["_rows"], result["_dataset"]
    save_role_outputs(result, val_dir, methods, args.figures_per_scene)
    extra_figs = save_gain_loss_figures(rows_copy, ds_copy, methods, conf, stats_map, val_dir)
    saved = json.loads((val_dir / "results.json").read_text(encoding="utf-8"))
    saved["figures"] = list(saved.get("figures", [])) + extra_figs
    saved["patch_distribution"] = result["patch_distribution"]
    (val_dir / "results.json").write_text(json.dumps(saved, indent=2), encoding="utf-8")

    (out / "METHOD.txt").write_text(json.dumps({**METHOD_DOC, "beta": best_beta}, indent=2), encoding="utf-8")
    (out / "tune_beta.json").write_text(json.dumps({"best_beta": best_beta, "records": tune_records}, indent=2),
                                        encoding="utf-8")
    readme = [
        "PHYSICS-AWARE REFINEMENT VALIDATION (v1)",
        "=" * 60,
        EXPERIMENT_LABEL,
        "",
        f"Frozen beta={best_beta} from {len(tune_idx)} tune patches (seed {args.tune_seed}).",
        f"Reported metrics on {len(eval_idx)} held-out validation patches within Kerala.",
        "Locked test scenes were NOT evaluated.",
        "",
        val_dir.joinpath("report.txt").read_text(encoding="utf-8"),
    ]
    (out / "README_results.txt").write_text("\n".join(readme), encoding="utf-8")
    logger.info("Done. beta=%s  out=%s", best_beta, out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
